def _basic_key_placement(map_id: str, label: str, position: Position) -> MapDefinition:
    row, col = position
    if DEFAULT_MAP[row][col] != Tile.FLOOR.value:
        raise ValueError("An alternate key position must be a floor tile.")
    rows = [line.replace(Tile.KEY.value, Tile.FLOOR.value) for line in DEFAULT_MAP]
    rows[row] = rows[row][:col] + Tile.KEY.value + rows[row][col + 1:]
    return MapDefinition(
        map_id, f"기본 15x15 · {label} 열쇠", f"열쇠 위치 {position}", MazeLayout(tuple(rows)),
    )


